/**
 * Returns model by matching its full ID or provider/model slug pair.
 */
export function getModelById(id: string): UnifiedCatalogModel | undefined {
  const normalized = id.toLowerCase();
  return UNIFIED_MODELS.find(
    (m) => m.id.toLowerCase() === normalized || `${m.providerSlug}/${m.modelSlug}`.toLowerCase() === normalized
  );
}

